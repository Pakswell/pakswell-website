  function language() {
    var lang = null;
    try { lang = new URLSearchParams(location.search).get("lang"); } catch (e) {}
    if (COPY[lang]) return lang;
    try { lang = localStorage.getItem("pw_lang"); } catch (e) {}
    return COPY[lang] ? lang : "en";
  }

  function el(tag, text, className) {
    var node = document.createElement(tag);
    if (text) node.textContent = text;
    if (className) node.className = className;
    return node;
  }

  function render(lang) {
    var t = COPY[lang];
    if (!t) return;
    document.documentElement.lang = lang;
    document.title = t.title + " - PAKSWELL";
    var tagline = document.querySelector(".brand-copy span");
    if (tagline) tagline.textContent = t.tagline;
    var back = document.querySelector(".home-link");
    if (back) { back.textContent = t.back; back.href = "/?lang=" + encodeURIComponent(lang); }

    var main = document.querySelector("main");
    main.textContent = "";
    var header = el("div", "", "page-header");
    header.appendChild(el("h1", t.title));
    header.appendChild(el("p", t.updated, "last-updated"));
    main.appendChild(header);
    t.sections.forEach(function (section) {
      var wrapper = el("section");
      wrapper.appendChild(el("h2", section[0]));
      section[1].forEach(function (paragraph) { wrapper.appendChild(el("p", paragraph)); });
      main.appendChild(wrapper);
    });
    var contact = el("div", "", "contact-info");
    var email = el("a", "mark.lee@pakswell.com");
    email.href = "mailto:mark.lee@pakswell.com";
    contact.appendChild(email);
    main.appendChild(contact);

    var footerCopy = document.querySelector("footer .footer-content p:last-child");
    if (footerCopy) footerCopy.textContent = t.footer;
    var footerLinks = document.querySelectorAll("footer .footer-links a");
    if (footerLinks[0]) { footerLinks[0].textContent = t.home; footerLinks[0].href = "/?lang=" + encodeURIComponent(lang); }
    if (footerLinks[1]) { footerLinks[1].textContent = t.policy; footerLinks[1].href = "/privacy?lang=" + encodeURIComponent(lang); }
    var copyright = document.querySelector("footer > .container > p");
    if (copyright) copyright.textContent = t.rights;
  }

  render(language());
